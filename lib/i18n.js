export const TRANSLATIONS = { en, id, ms, tr }

export function translate(lang, key, vars, fallback) {
  let fallbackText = fallback
  let variables = vars
  if (typeof vars === 'string' && fallback === undefined) {
    fallbackText = vars
    variables = undefined
  }
  const dict = TRANSLATIONS?.[lang] || en
  let s = dict?.[key] ?? en?.[key] ?? fallbackText ?? key
  if (typeof s === 'string' && variables && typeof variables === 'object') {
    Object.entries(variables).forEach(([k, v]) => {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), v)
    })
  }
  return s
}

