import { Buffer } from 'node:buffer';
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const CRATE_MANIFEST = path.join(REPO_ROOT, 'rust', 'arshif-core', 'Cargo.toml');
const RAW_WASM_PATH = path.join(
  REPO_ROOT,
  'rust',
  'arshif-core',
  'target',
  'wasm32-unknown-unknown',
  'release',
  'arshif_core.wasm',
);
const ARTIFACT_PATH = path.join(REPO_ROOT, 'src', 'lib', 'rust', 'wasmArtifact.ts');

const STRIPPED_CUSTOM_SECTIONS = new Set(['name', 'producers']);

function buildEnvWithCargo() {
  const home = os.homedir();
  const cargoHome = process.env.CARGO_HOME || path.join(home, '.cargo');
  const cargoBin = path.join(cargoHome, 'bin');
  const currentPath = process.env.PATH ?? '';
  const pathEntries = currentPath.split(path.delimiter);
  const nextPath =
    fs.existsSync(cargoBin) && !pathEntries.includes(cargoBin)
      ? `${cargoBin}${path.delimiter}${currentPath}`
      : currentPath;
  const remapFlags = [
    `--remap-path-prefix=${cargoHome}=/cargo`,
    `--remap-path-prefix=${REPO_ROOT}=/workspace`,
    `--remap-path-prefix=${home}=/home`,
  ].join(' ');
  const prevRustFlags = process.env.RUSTFLAGS ? `${process.env.RUSTFLAGS} ` : '';
  return { ...process.env, PATH: nextPath, RUSTFLAGS: `${prevRustFlags}${remapFlags}` };
}

function readVarUint32(buf, offset) {
  let result = 0;
  let shift = 0;
  let pos = offset;
  while (pos < buf.length) {
    const byte = buf[pos++];
    result |= (byte & 0x7f) << shift;
    if ((byte & 0x80) === 0) {
      return { value: result >>> 0, nextOffset: pos };
    }
    shift += 7;
    if (shift > 35) throw new Error('Invalid LEB128 varuint32 in WASM binary');
  }
  throw new Error('Unexpected EOF reading LEB128 varuint32 in WASM binary');
}

function shouldStripCustomSection(sectionName) {
  return (
    STRIPPED_CUSTOM_SECTIONS.has(sectionName) ||
    sectionName.startsWith('.debug') ||
    sectionName.startsWith('linking')
  );
}

/**
 * Strips non-essential custom WASM sections (`name`, `producers`, `.debug_*`) while preserving
 * every executable and data section verbatim.
 */
function stripCustomSections(wasmBytes) {
  if (
    wasmBytes.length < 8 ||
    wasmBytes[0] !== 0x00 ||
    wasmBytes[1] !== 0x61 ||
    wasmBytes[2] !== 0x73 ||
    wasmBytes[3] !== 0x6d
  ) {
    throw new Error('Invalid WASM magic header');
  }

  const chunks = [wasmBytes.subarray(0, 8)];
  let pos = 8;
  while (pos < wasmBytes.length) {
    const sectionStart = pos;
    const sectionId = wasmBytes[pos++];
    const { value: sectionSize, nextOffset: payloadStart } = readVarUint32(wasmBytes, pos);
    const sectionEnd = payloadStart + sectionSize;
    if (sectionEnd > wasmBytes.length) {
      throw new Error(`WASM section ${sectionId} exceeds file bounds`);
    }

    let keep = true;
    if (sectionId === 0) {
      const { value: nameLen, nextOffset: nameStart } = readVarUint32(wasmBytes, payloadStart);
      const nameEnd = nameStart + nameLen;
      if (nameEnd <= sectionEnd) {
        const name = Buffer.from(wasmBytes.subarray(nameStart, nameEnd)).toString('utf8');
        if (shouldStripCustomSection(name)) {
          keep = false;
        }
      }
    }

    if (keep) {
      chunks.push(wasmBytes.subarray(sectionStart, sectionEnd));
    }
    pos = sectionEnd;
  }

  return Buffer.concat(chunks);
}

function validateWasm(wasmBytes) {
  const mod = new WebAssembly.Module(wasmBytes);
  const imports = WebAssembly.Module.imports(mod);
  if (imports.length > 0) {
    throw new Error(`Expected zero host imports in arshif-core WASM, got: ${JSON.stringify(imports)}`);
  }
  const inst = new WebAssembly.Instance(mod, {});
  const versionFn = inst.exports.arshif_version;
  if (typeof versionFn !== 'function' || versionFn() !== 1) {
    throw new Error(`Unexpected arshif_version() result from WASM artifact: ${String(versionFn)}`);
  }
}

function renderArtifactTs(wasmBytes) {
  const sha256 = crypto.createHash('sha256').update(wasmBytes).digest('hex');
  const base64 = wasmBytes.toString('base64');
  return [
    '// Auto-generated by scripts/build-rust.mjs. Do not edit manually.',
    `export const WASM_BYTE_LENGTH = ${wasmBytes.length};`,
    `export const WASM_SHA256 = '${sha256}';`,
    `export const WASM_BASE64 = '${base64}';`,
    '',
  ].join('\n');
}

function exportSignature(wasmBytes) {
  const mod = new WebAssembly.Module(wasmBytes);
  return WebAssembly.Module.exports(mod)
    .map((e) => `${e.kind}:${e.name}`)
    .sort()
    .join(',');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const ciVerify = process.argv.includes('--ci-verify');
  const env = buildEnvWithCargo();

  execFileSync(
    'cargo',
    ['build', '--manifest-path', CRATE_MANIFEST, '--target', 'wasm32-unknown-unknown', '--release', '--locked'],
    { cwd: REPO_ROOT, env, stdio: 'inherit' },
  );

  const rawWasm = fs.readFileSync(RAW_WASM_PATH);
  const strippedWasm = stripCustomSections(rawWasm);
  validateWasm(strippedWasm);

  const generated = renderArtifactTs(strippedWasm);
  const sha256 = crypto.createHash('sha256').update(strippedWasm).digest('hex');

  if (ciVerify) {
    if (!fs.existsSync(ARTIFACT_PATH)) {
      console.error(`Missing ${path.relative(REPO_ROOT, ARTIFACT_PATH)}. Run: npm run build:rust`);
      process.exit(1);
    }
    const existing = fs.readFileSync(ARTIFACT_PATH, 'utf8');
    const b64Match = /export const WASM_BASE64 = '([A-Za-z0-9+/=]+)';/.exec(existing);
    const lenMatch = /export const WASM_BYTE_LENGTH = (\d+);/.exec(existing);
    const shaMatch = /export const WASM_SHA256 = '([0-9a-f]{64})';/.exec(existing);
    if (!b64Match || !lenMatch || !shaMatch) {
      console.error(`Malformed ${path.relative(REPO_ROOT, ARTIFACT_PATH)}.`);
      process.exit(1);
    }
    const committedBytes = Buffer.from(b64Match[1], 'base64');
    const committedSha = crypto.createHash('sha256').update(committedBytes).digest('hex');
    if (committedBytes.length !== Number(lenMatch[1]) || committedSha !== shaMatch[1]) {
      console.error(`Committed WASM metadata mismatch in ${path.relative(REPO_ROOT, ARTIFACT_PATH)}.`);
      process.exit(1);
    }
    validateWasm(committedBytes);
    if (exportSignature(committedBytes) !== exportSignature(strippedWasm)) {
      console.error(
        `Exported WASM ABI symbols in ${path.relative(REPO_ROOT, ARTIFACT_PATH)} differ from rust/arshif-core. Run: npm run build:rust`,
      );
      process.exit(1);
    }
    console.log(
      `[build-rust] OK (--ci-verify): fresh wasm32 build (${strippedWasm.length}B) and committed artifact (${committedBytes.length}B, sha256=${committedSha.slice(0, 12)}) ABI-verified`,
    );
    return;
  }

  if (checkOnly) {
    if (!fs.existsSync(ARTIFACT_PATH)) {
      console.error(`Missing ${path.relative(REPO_ROOT, ARTIFACT_PATH)}. Run: npm run build:rust`);
      process.exit(1);
    }
    const existing = fs.readFileSync(ARTIFACT_PATH, 'utf8');
    if (existing !== generated) {
      console.error(
        `WASM artifact drift detected in ${path.relative(REPO_ROOT, ARTIFACT_PATH)} (expected sha256=${sha256}, bytes=${strippedWasm.length}). Run: npm run build:rust`,
      );
      process.exit(1);
    }
    console.log(
      `[build-rust] OK (--check): ${path.relative(REPO_ROOT, ARTIFACT_PATH)} matches fresh build (${strippedWasm.length} bytes, sha256=${sha256.slice(0, 12)})`,
    );
    return;
  }

  fs.mkdirSync(path.dirname(ARTIFACT_PATH), { recursive: true });
  fs.writeFileSync(ARTIFACT_PATH, generated, 'utf8');
  console.log(
    `[build-rust] Wrote ${path.relative(REPO_ROOT, ARTIFACT_PATH)} (${rawWasm.length} -> ${strippedWasm.length} bytes, sha256=${sha256.slice(0, 12)})`,
  );
}

main();
